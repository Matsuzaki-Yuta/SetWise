
"""Amazon Bedrock integration for SetWise."""

import os

import boto3
from flask import current_app


def get_bedrock_client():
    """Create the Bedrock Runtime client."""
    return boto3.client(
        "bedrock-runtime",
        region_name=current_app.config["AWS_REGION"],
    )


def test_bedrock_connection():
    """Test whether SetWise can invoke a Bedrock model."""
    model_id = os.environ["BEDROCK_MODEL_ID"]
    client = get_bedrock_client()

    response = client.converse(
        modelId=model_id,
        messages=[
            {
                "role": "user",
                "content": [
                    {
                        "text": (
                            "You are assisting an indoor bouldering "
                            "route setter. Briefly explain how a V4 "
                            "compression climb on a 45-degree overhang "
                            "might differ from a V4 balance climb "
                            "on a slab."
                        )
                    }
                ],
            }
        ],
        inferenceConfig={
            "maxTokens": 400,
        },
    )

    return "\n".join(
        block["text"]
        for block in response["output"]["message"]["content"]
        if "text" in block
    )


from app.services.agent_tools import (
    get_setting_gaps,
    get_climb_combination_distribution,
)


# Tools the AI is allowed to request.
TOOL_CONFIG = {
    "tools": [
        {
            "toolSpec": {
                "name": "get_setting_gaps",
                "description": (
                    "Calculate remaining grade, subgrade and style "
                    "deficits after selected walls are reset."
                ),
                "inputSchema": {
                    "json": {
                        "type": "object",
                        "properties": {},
                    }
                },
            }
        },
        {
            "toolSpec": {
                "name": "get_climb_combinations",
                "description": (
                    "Analyse existing climb combinations of grade, "
                    "subgrade, climbing style and wall terrain, "
                    "excluding selected reset walls."
                ),
                "inputSchema": {
                    "json": {
                        "type": "object",
                        "properties": {},
                    }
                },
            }
        },
    ]
}


def run_analysis_agent(gym_id, selected_wall_ids):
    """
    Ask Bedrock to analyse a setting day using read-only
    Python tools. Does not save or modify gym inventory.
    """
    if not selected_wall_ids:
        raise ValueError("At least one wall must be selected")

    client = get_bedrock_client()
    model_id = os.environ["BEDROCK_MODEL_ID"]

    # The gym identity and selected walls are controlled by
    # our application, NOT by arguments generated by the AI.
    allowed_tools = {
        "get_setting_gaps": lambda: get_setting_gaps(gym_id, selected_wall_ids),
        "get_climb_combinations": lambda: get_climb_combination_distribution(gym_id, selected_wall_ids),
    }

    system_prompt = """
    You are SetWise, an assistant for experienced indoor
    bouldering route setters.

    Your role is to understand the overall climbing experience,
    not simply fill numerical grade deficits.

    Consider:
    - Grade and subgrade distribution.
    - Climbing styles and movement characteristics.
    - Wall angles and terrain suitability.
    - Variety of climbing experiences throughout the gym.
    - Targets defined by the head setter.

    Use the available tools to analyse the gym.

    Give practical setting recommendations with:
    1. Recommended grade, style and wall.
    2. Intended climbing character or movement concept.
    3. Why it fits the existing gym inventory.
    4. A creative movement inspiration for the setter.

    Treat grades and movement suggestions as proposals,
    not guarantees of physical difficulty.

    Do not claim that a climb has actually been set.
    """

    messages = [
        {
            "role": "user",
            "content": [{
                "text": (
                    f"Analyse a setting day for gym {gym_id}. "
                    f"The selected wall IDs are "
                    f"{selected_wall_ids}. "
                    "Call get_setting_gaps and "
                    "get_climb_combinations before making "
                    "recommendations. "
                    "Provide a brief overview and three "
                    "example climb ideas with explanations."
                )
            }],
        }
    ]

    tool_calls = []
    final_text = None

    # Limit model iterations to avoid runaway requests.
    for _ in range(6):
        response = client.converse(
            modelId=model_id,
            system=[{"text": system_prompt}],
            messages=messages,
            toolConfig=TOOL_CONFIG,
            inferenceConfig={
                "maxTokens": 2000,
            },
        )

        output_message = response["output"]["message"]
        messages.append(output_message)

        if response["stopReason"] == "tool_use":
            results = []

            for block in output_message["content"]:
                if "toolUse" not in block:
                    continue

                tool_use = block["toolUse"]
                tool_name = tool_use["name"]
                tool_id = tool_use["toolUseId"]

                if tool_name not in allowed_tools:
                    raise ValueError(
                        f"Unrecognised AI tool: {tool_name}"
                    )

                print("Bedrock requested:", tool_name)
                tool_calls.append(tool_name)

                # Execute the real Python analysis function.
                data = allowed_tools[tool_name]()

                results.append({
                    "toolResult": {
                        "toolUseId": tool_id,
                        "content": [{"json": data}],
                    }
                })

            if not results:
                raise RuntimeError(
                    "Bedrock requested tools but provided none"
                )

            messages.append({
                "role": "user",
                "content": results,
            })
            continue

        if response["stopReason"] != "end_turn":
            raise RuntimeError(
                "Bedrock stopped before completing: "
                + response["stopReason"]
            )

        final_text = "\n".join(
            block["text"]
            for block in output_message["content"]
            if "text" in block
        )
        break

    if final_text is None:
        raise RuntimeError(
            "Agent exceeded the maximum tool iterations"
        )

    expected_tools = {
        "get_setting_gaps",
        "get_climb_combinations",
    }

    if not expected_tools.issubset(set(tool_calls)):
        raise RuntimeError(
            "Bedrock did not call both required tools. "
            f"Called: {tool_calls}"
        )

    return {
        "gym_id": gym_id,
        "selected_wall_ids": selected_wall_ids,
        "tools_called": tool_calls,
        "analysis": final_text,
    }
